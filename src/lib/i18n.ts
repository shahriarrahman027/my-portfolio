export function getTranslations(locale: Locale) {
  return translations[locale] || translations.en;
}

export function getLocalizedPath(currentUrl: URL | string, targetLocale: Locale): string {
  const url = typeof currentUrl === 'string' ? new URL(currentUrl, 'http://localhost') : currentUrl;
  const pathname = url.pathname;
  
  // Extract locale from path
  const segments = pathname.split('/').filter(Boolean);
  if (segments.length > 0 && (segments[0] === 'en' || segments[0] === 'bn')) {
    segments[0] = targetLocale;
  } else {
    segments.unshift(targetLocale);
  }

  return '/' + segments.join('/') + (url.search || '');
}

